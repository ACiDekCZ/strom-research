export type UIKey = keyof typeof UI;

/** A text for the person, in their language. */
export function ui(lang: string, key: UIKey, values: Record<string, string | number> = {}): string {
  return localized(lang, key, UI[key], values);
}

/**
 * A command's placeholders as a person reads them (<input> → <podklad>, "<Given /Surname/>" → "<Jméno /Příjmení/>"):
 * those the catalog names (ui.arg.*), the rest as they are — the values a command takes literally (user|research).
 */
export function placeholders(lang: string, text: string): string {
  return text.replace(/<([^<>\n]+)>/g, (all, inner: string) => {
    const key = `ui.arg.${inner.toLowerCase().replace(/[^\p{L}\p{N}]+/gu, "-").replace(/^-+|-+$/g, "")}`;
    return key in UI ? `<${ui(lang, key as UIKey)}>` : all;
  });
}
